#!/usr/bin/env python3
"""Generate official native runners with the pinned SDK, then apply required permissions."""
import json, pathlib, plistlib, re, shutil, subprocess, sys, xml.etree.ElementTree as ET
ROOT=pathlib.Path(__file__).resolve().parents[1]; APP=ROOT/'apps/nearloop'
def run(args,**kwargs):return subprocess.run(args,check=True,**kwargs)
flutter=shutil.which('flutter')
if not flutter:sys.exit('Flutter is missing. Install stable 3.38.0 and add flutter/bin to PATH, then retry.')
version=json.loads(subprocess.check_output([flutter,'--version','--machine']))['frameworkVersion']
if version!='3.38.0':sys.exit(f'Expected Flutter 3.38.0; found {version}. Use the pinned SDK.')
# Native files are generated by Flutter, not hand-written approximations of Xcode/Gradle projects.
run([flutter,'create','--no-pub','--platforms=android,ios,macos,windows','--org','app.nearloop','--project-name','nearloop','.'],cwd=APP)
android=APP/'android/app/src/main/AndroidManifest.xml'
ns='http://schemas.android.com/apk/res/android';ET.register_namespace('android',ns)
tree=ET.parse(android);root=tree.getroot()
for permission in ['INTERNET','CHANGE_WIFI_MULTICAST_STATE']:
    name='android.permission.'+permission
    if not any(e.get('{'+ns+'}name')==name for e in root.findall('uses-permission')):
        ET.SubElement(root,'uses-permission',{'{'+ns+'}name':name})
application=root.find('application');application.set('{'+ns+'}label','NearLoop');application.set('{'+ns+'}allowBackup','false')
tree.write(android,encoding='utf-8',xml_declaration=True)
for platform in ['ios','macos']:
    info=APP/platform/'Runner/Info.plist'
    with info.open('rb') as f:data=plistlib.load(f)
    data.update(NSLocalNetworkUsageDescription='Discover and join spaces you choose on your local network.',NSBonjourServices=['_nearloop._tcp'],CFBundleDisplayName='NearLoop')
    with info.open('wb') as f:plistlib.dump(data,f)
    if platform=='macos':
        project=APP/'macos/Runner.xcodeproj/project.pbxproj'
        text=project.read_text()
        # Raise older generated targets without lowering a user's newer target.
        text=re.sub(r'MACOSX_DEPLOYMENT_TARGET = ([0-9.]+);',
                    lambda m: 'MACOSX_DEPLOYMENT_TARGET = 12.0;' if tuple(map(int,m[1].split('.'))) < (12,0) else m[0],text)
        # Keychain access groups need development signing, not ad-hoc signing.
        text=re.sub(r'(CODE_SIGN_ENTITLEMENTS = Runner/(?:DebugProfile|Release)\.entitlements;\n)([ \t]*)(CODE_SIGN_STYLE =)',
                    lambda m: m[1]+m[2]+'CODE_SIGN_IDENTITY = "Apple Development";\n'+m[2]+m[3],text)
        project.write_text(text)
        for entitlement in (APP/platform/'Runner').glob('*.entitlements'):
            with entitlement.open('rb') as f:data=plistlib.load(f)
            data.update({'com.apple.security.network.client':True,'com.apple.security.network.server':True,'com.apple.security.files.user-selected.read-only':True,'keychain-access-groups':['$(AppIdentifierPrefix)app.nearloop.nearloop']})
            with entitlement.open('wb') as f:plistlib.dump(data,f)
    else:
        ent=APP/'ios/Runner/Runner.entitlements'
        with ent.open('wb') as f:plistlib.dump({'keychain-access-groups':['$(AppIdentifierPrefix)app.nearloop.nearloop']},f)
        project=APP/'ios/Runner.xcodeproj/project.pbxproj';text=project.read_text()
        if 'CODE_SIGN_ENTITLEMENTS = Runner/Runner.entitlements;' not in text:
            text=text.replace('PRODUCT_BUNDLE_IDENTIFIER =','CODE_SIGN_ENTITLEMENTS = Runner/Runner.entitlements;\n\t\t\t\tPRODUCT_BUNDLE_IDENTIFIER =')
        project.write_text(text)
run([flutter,'pub','get'],cwd=APP)
print('Runners generated and dependencies resolved. Review and commit pubspec.lock and generated runners.')
